// Regenerates assets/hsk_levels.tsv from a checkout of complete-hsk-vocabulary.
//
// Usage:
//   git clone --depth 1 https://github.com/drkameleon/complete-hsk-vocabulary /tmp/hsk
//   dart run tool/build_hsk_levels.dart /tmp/hsk
import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  if (args.length != 1) {
    stderr.writeln('usage: dart run tool/build_hsk_levels.dart <checkout>');
    exit(64);
  }
  final checkout = args.single;

  // Exclusive lists hold only the words new at each level; keep the lowest
  // level should a word appear twice.
  final levels = <String, int>{};
  for (var level = 1; level <= 6; level++) {
    final file = File('$checkout/wordlists/exclusive/old/$level.json');
    for (final e in jsonDecode(file.readAsStringSync()) as List) {
      levels.putIfAbsent((e as Map)['simplified'] as String, () => level);
    }
  }

  final out = StringBuffer()
    ..writeln('# Old HSK (HSK 2.0, 2010) vocabulary, levels 1-6, simplified.')
    ..writeln('# Format: level<TAB>word. Generated by tool/build_hsk_levels.dart')
    ..writeln('# from complete-hsk-vocabulary, wordlists/exclusive/old/*.json:')
    ..writeln('# https://github.com/drkameleon/complete-hsk-vocabulary')
    ..writeln('# MIT License, Copyright (c) 2026 Yanis Zafiropulos.');
  levels.forEach((word, level) => out.writeln('$level\t$word'));
  File('assets/hsk_levels.tsv').writeAsStringSync(out.toString());
  stdout.writeln('${levels.length} words written to assets/hsk_levels.tsv');
}
